export function getRolePermissionScope(role: MembershipRole, action: PermissionAction): AccessScope {
  return PERMISSION_MATRIX[role]?.[action] ?? 'no';
}

export function isActionAllowed(role: MembershipRole, action: PermissionAction): boolean {
  const scope = getRolePermissionScope(role, action);
  return scope !== 'no';
}
